#!/usr/bin/env node
// Builds the frosted family from src/frosted.mjs.
//
//   dist/frosted/svg/<name>.svg       standalone 64×64 illustrations (filters inside)
//   dist/frosted/png/<name>@{1x,2x,3x}.png   128/256/384 px renditions for the apps + roundels
//   dist/frosted/index.js / .d.ts     names, markup map, frostedForCategory(path)
//   docs/frosted.html                 contact sheet on the pale ground
//
// PNG rendering needs the optional devDependency `sharp`; without it the
// script writes everything else and says so.

import { mkdirSync, writeFileSync, rmSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { frosted, FROSTED_BY_CATEGORY, HUES, FROSTED_GRID as G } from '../src/frosted.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist', 'frosted');
rmSync(out, { recursive: true, force: true });
for (const d of ['svg', 'png']) mkdirSync(join(out, d), { recursive: true });

const seen = new Set();
for (const f of frosted) {
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(f.name)) throw new Error(`bad name ${f.name}`);
  if (seen.has(f.name)) throw new Error(`duplicate ${f.name}`);
  seen.add(f.name);
  if (!HUES[f.hue]) throw new Error(`${f.name}: unknown hue ${f.hue}`);
  if (!f.back || !f.glass?.length) throw new Error(`${f.name}: needs back + glass`);
  if (/#[0-9a-f]{3,6}/i.test(f.back.replace(/#fff\b/gi, '')) ) throw new Error(`${f.name}: hard-coded colour in back — use url(#g)/url(#g2)`);
}

// Every id is prefixed with the icon name so many icons can be inlined in
// one HTML document without the first icon's gradient winning for all of them.
const defs = (hue, p) => {
  const [a, b, c] = HUES[hue];
  return `<defs><linearGradient id="${p}g" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${a}"/><stop offset="1" stop-color="${b}"/></linearGradient><linearGradient id="${p}g2" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="${b}"/><stop offset="1" stop-color="${c}"/></linearGradient><filter id="${p}blur" x="-30%" y="-30%" width="160%" height="160%"><feGaussianBlur stdDeviation="2.4"/></filter><filter id="${p}sh" x="-40%" y="-40%" width="180%" height="200%"><feDropShadow dx="0" dy="5" stdDeviation="4" flood-color="#1E3A5F" flood-opacity=".22"/></filter><filter id="${p}sh2" x="-40%" y="-40%" width="180%" height="200%"><feDropShadow dx="0" dy="3" stdDeviation="3" flood-color="#1E3A5F" flood-opacity=".12"/></filter></defs>`;
};

export const svgFor = (f, { size = G, ground = null } = {}) => {
  const p = `mf-${f.name}-`;
  const back = f.back.replace(/url\(#g2\)/g, `url(#${p}g2)`).replace(/url\(#g\)/g, `url(#${p}g)`);
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${G} ${G}" width="${size}" height="${size}">${defs(f.hue, p)}<defs><g id="${p}b">${back}</g><clipPath id="${p}c">${f.glass.map((d) => `<path d="${d}"/>`).join('')}</clipPath></defs>${ground ? `<rect width="${G}" height="${G}" fill="${ground}"/>` : ''}<g transform="${f.zoom ? `translate(${G / 2} ${G / 2}) scale(${f.zoom}) translate(${-G / 2} ${-G / 2})` : ''}"><g filter="url(#${p}sh2)"><use href="#${p}b" xlink:href="#${p}b"/></g><g filter="url(#${p}sh)"><g clip-path="url(#${p}c)"><rect width="${G}" height="${G}" fill="#fff" fill-opacity=".35"/><use href="#${p}b" xlink:href="#${p}b" filter="url(#${p}blur)" opacity=".85"/></g>${f.glass.map((d) => `<path d="${d}" fill="url(#${p}g)" fill-opacity=".10"/><path d="${d}" fill="#fff" fill-opacity=".46"/>`).join('')}${f.glass.map((d) => `<path d="${d}" fill="none" stroke="#fff" stroke-opacity=".95" stroke-width=".9"/>`).join('')}${f.front ? `<g>${f.front.replace(/url\(#g2\)/g, `url(#${p}g2)`).replace(/url\(#g\)/g, `url(#${p}g)`)}</g>` : ''}<g fill="#fff" fill-opacity=".92">${f.detail ?? ''}</g></g></g></svg>`;
};

for (const f of frosted) writeFileSync(join(out, 'svg', `${f.name}.svg`), svgFor(f) + '\n');

writeFileSync(join(out, 'index.js'), [
  `// Generated by scripts/build-frosted.mjs — do not edit.`,
  `export const FROSTED_GRID = ${G};`,
  `export const HUES = ${JSON.stringify(HUES)};`,
  `export const FROSTED = ${JSON.stringify(Object.fromEntries(frosted.map((f) => [f.name, { category: f.category, hue: f.hue, svg: svgFor(f) }])))};`,
  `export const names = Object.keys(FROSTED);`,
  `export const FROSTED_BY_CATEGORY = ${JSON.stringify(FROSTED_BY_CATEGORY)};`,
  `/** Frosted icon name for a category path, nearest mapped ancestor wins; null when nothing matches. */`,
  `export const frostedForCategory = (path) => { const parts = String(path || '').split('/'); while (parts.length) { const hit = FROSTED_BY_CATEGORY[parts.join('/')]; if (hit) return hit; parts.pop(); } return null; };`,
  `/** Standalone <svg> markup; pass size in px. */`,
  `export const svg = (name, size = ${G}) => { const f = FROSTED[name]; if (!f) throw new Error('Unknown MBX frosted icon: ' + name); return f.svg.replace(/width="\\d+" height="\\d+"/, 'width="' + size + '" height="' + size + '"'); };`,
  `/** Path under the package for a PNG rendition: png(name, 2) → "png/<name>@2x.png" (128·scale px). */`,
  `export const png = (name, scale = 2) => 'png/' + name + '@' + scale + 'x.png';`,
  `/** Roundel rendition (pale disc, icon inset, theme-independent): roundel(name, 2) → "roundel/<name>@2x.png". */`,
  `export const roundel = (name, scale = 2) => 'roundel/' + name + '@' + scale + 'x.png';`,
  '',
].join('\n'));
writeFileSync(join(out, 'index.d.ts'), [
  `export type MbxFrostedName = ${frosted.map((f) => JSON.stringify(f.name)).join(' | ')};`,
  `export type MbxFrostedCategory = ${frosted.map((f) => JSON.stringify(f.category)).join(' | ')};`,
  `export declare const FROSTED_GRID: number;`,
  `export declare const HUES: Record<string, [string, string, string]>;`,
  `export declare const FROSTED: Record<MbxFrostedName, { category: MbxFrostedCategory; hue: string; svg: string }>;`,
  `export declare const names: MbxFrostedName[];`,
  `export declare const FROSTED_BY_CATEGORY: Record<MbxFrostedCategory, MbxFrostedName>;`,
  `export declare function frostedForCategory(path: string | null | undefined): MbxFrostedName | null;`,
  `export declare function svg(name: MbxFrostedName, size?: number): string;`,
  `export declare function png(name: MbxFrostedName, scale?: 1 | 2 | 3): string;`,
  `export declare function roundel(name: MbxFrostedName, scale?: 1 | 2 | 3): string;`,
  '',
].join('\n'));

export const ROUNDEL_GROUND = '#EEF2F8';
export const ROUNDEL_INSET = 0.78;
/** Roundel: the icon inset on a pale disc, so it reads the same on light and dark UI and nothing is clipped by a circular mask. */
export const roundelSvgFor = (f, { size = G } = {}) => {
  const inner = svgFor(f).replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const t = (G * (1 - ROUNDEL_INSET)) / 2;
  return `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" viewBox="0 0 ${G} ${G}" width="${size}" height="${size}"><circle cx="${G / 2}" cy="${G / 2}" r="${G / 2}" fill="${ROUNDEL_GROUND}"/><g transform="translate(${t} ${t}) scale(${ROUNDEL_INSET})">${inner}</g></svg>`;
};
mkdirSync(join(out, 'roundel'), { recursive: true });
for (const f of frosted) writeFileSync(join(out, 'roundel', `${f.name}.svg`), roundelSvgFor(f) + '\n');

// ── preview ────────────────────────────────────────────────────────
const roundels = frosted.filter((f) => !f.category.includes('/')).map((f) => `<div class="r"><div class="ring">${roundelSvgFor(f, { size: 72 })}</div><span>${f.category}</span></div>`).join('');
const cells = frosted.map((f) => `<div class="c" title="${f.category}">${svgFor(f, { size: 112 })}<span>${f.name}</span><small>${f.category}</small></div>`).join('');
writeFileSync(join(root, 'docs', 'frosted.html'), `<!doctype html><meta charset="utf-8"><title>MBX Frosted</title><style>body{margin:0;padding:32px;background:#EEF2F8;color:#3A4250;font:13px/1.4 "IBM Plex Sans",system-ui,sans-serif}h1{font:600 28px/1 Oswald,"Arial Narrow",sans-serif;text-transform:uppercase;margin:0 0 6px}p{margin:0 0 24px;color:#6B7483;max-width:62ch}.g{display:grid;grid-template-columns:repeat(auto-fill,minmax(150px,1fr));gap:18px 8px}.c{display:flex;flex-direction:column;align-items:center;gap:2px;text-align:center}.c span{font-family:"IBM Plex Mono",Menlo,monospace;font-size:12px}.c small{color:#8A93A3;font-size:11px}.dark{background:#14171D;color:#E6E8EC;border-radius:12px;padding:20px 24px;margin:0 0 28px}.dark h2{font:500 18px/1.2 Oswald,"Arial Narrow",sans-serif;text-transform:uppercase;margin:0 0 4px}.dark p{color:#9AA1AC;margin:0 0 16px}.rg{display:flex;flex-wrap:wrap;gap:14px 18px}.r{display:flex;flex-direction:column;align-items:center;gap:6px;width:84px;text-align:center;font-size:11px;color:#C9CED6}.ring{width:78px;height:78px;border-radius:50%;border:2px solid rgba(255,200,5,.55);background:rgba(255,200,5,.08);display:grid;place-items:center}.ring svg{border-radius:50%}</style><h1>MBX Frosted</h1><p>${frosted.length} illustrated icons, one per service-category node: a gradient object behind a frosted plate. For roundels, empty states and the website — 48 px and up.</p><div class="dark"><h2>Category roundels, dark theme</h2><p>The roundel rendition carries its own pale disc, so it reads the same on the client app's dark Home as on a white card. The gold ring is the app's.</p><div class="rg">${roundels}</div></div><div class="g">${cells}</div>`);

// ── PNG renditions (optional: sharp) ───────────────────────────────
let sharp = null;
try { sharp = (await import('sharp')).default; } catch { console.warn('sharp not installed — PNG renditions skipped (npm i -D sharp)'); }
if (sharp) {
  for (const f of frosted) {
    for (const scale of [1, 2, 3]) {
      const px = 128 * scale;
      await sharp(Buffer.from(svgFor(f, { size: px }))).png().toFile(join(out, 'png', `${f.name}@${scale}x.png`));
      await sharp(Buffer.from(roundelSvgFor(f, { size: px }))).png().toFile(join(out, 'roundel', `${f.name}@${scale}x.png`));
    }
  }
}
console.log(`built ${frosted.length} frosted icons → dist/frosted/ (${sharp ? 'svg + png' : 'svg only'}) and docs/frosted.html`);
